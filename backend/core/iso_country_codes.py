"""ISO 3166-1 alpha-2 country codes.

Used to validate free-text "target market" fields so a project can't end up
with a made-up abbreviation (e.g. "GLO" for "Global") instead of a real
country code. That kind of bad data doesn't just fail silently: it flows
straight into AI prompt context (e.g. `"market": "glo"`), and when other
brand-identity signals are weak (missing title/meta/H1), a model can
misread it as the brand name itself.

There is deliberately no "global"/"worldwide" pseudo-code here: a project
with no single target market should leave this field unset rather than
invent a code for it.
"""

