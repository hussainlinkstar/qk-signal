export type VatValidationResult = {
  valid: boolean;
  countryCode: string | null;
  message: string;
};

export function validateVatFormat(vat: string): VatValidationResult {
  const cleaned = vat.replace(/[\s.-]/g, "").toUpperCase();

  if (cleaned.length < 4) {
    return { valid: false, countryCode: null, message: "VAT number is too short." };
  }

  // Try to detect country prefix (first 2 chars)
  const prefix = cleaned.slice(0, 2);

  // Greece uses EL but country code is GR
  const countryCode = prefix === "EL" ? "GR" : prefix;

  const pattern = VAT_PATTERNS[prefix];
  if (!pattern) {
    // Unknown prefix, allow freeform but note it's not a known EU VAT format
    return {
      valid: true,
      countryCode,
      message: "Format not validated (non-EU or unknown prefix).",
    };
  }

  if (pattern.test(cleaned)) {
    return { valid: true, countryCode, message: "Valid EU VAT format." };
  }

  return { valid: false, countryCode, message: `Invalid format for ${prefix} VAT number.` };
}

export function detectCountryFromVat(vat: string): string | null {
  const cleaned = vat.replace(/[\s.-]/g, "").toUpperCase();
  if (cleaned.length < 2) return null;
  const prefix = cleaned.slice(0, 2);
  if (prefix === "EL") return "GR";
  if (VAT_PATTERNS[prefix]) return prefix;
  // Check if the prefix matches an ISO country code at all
  if (COUNTRY_MAP.has(prefix)) return prefix;
  return null;
}
